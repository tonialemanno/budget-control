function language(locale = activeLocale) {
  return String(locale || 'de-CH').split('-')[0].toLowerCase();
}

export function normaliseLocale(locale) {
  const candidate = String(locale || '').trim();
  if (SUPPORTED.has(candidate)) return candidate;
  const lang = language(candidate);
  if (lang === 'it') return 'it-CH';
  if (lang === 'en') return 'en-CH';
  return 'de-CH';
}

export function setLocale(locale) {
  activeLocale = normaliseLocale(locale);
  if (typeof document !== 'undefined') document.documentElement.lang = language(activeLocale);
  return activeLocale;
}

export function getLocale() {
  return activeLocale;
}

export function getLanguage(locale = activeLocale) {
  return language(locale);
}

export function t(source, locale = activeLocale) {
  const text = String(source ?? '');
  const lang = language(locale);
  if (lang === 'de') return text;
  const dict = DICTS[lang];
  if (!dict) return text;
  const finish = (value) => {
    if (lang === 'it') return String(value).replace(/\bunbekannt\b/g, 'sconosciuto');
    if (lang === 'en') return String(value).replace(/\bunbekannt\b/g, 'unknown');
    return value;
  };
  let result = text;
  for (let pass = 0; pass < 4; pass += 1) {
    const direct = Object.prototype.hasOwnProperty.call(dict, result) ? dict[result] : null;
    if (direct !== null && direct !== result) {
      result = direct;
      continue;
    }
    let changed = false;
    for (const [pattern, replacement] of PATTERNS[lang] || []) {
      if (!pattern.test(result)) continue;
      const next = result.replace(pattern, replacement);
      if (next !== result) {
        result = next;
        changed = true;
      }
      break;
    }
    if (!changed) break;
  }
  return finish(result);
}

function shouldSkipNode(node) {
  const parent = node?.parentElement;
  if (!parent) return true;
  if (parent.closest('[data-i18n-ignore], .privacy-value, .amount, .account-name, .list-row-title, #profileName, #profileMeta, .profile-avatar')) return true;
  if (parent.matches('script,style,noscript')) return true;
  if (parent.matches('strong') && parent.closest('.mini-detail-list')) return true;
  return false;
}

function translateNode(node, locale) {
  if (shouldSkipNode(node)) return;
  const raw = node.nodeValue || '';
  const trimmed = raw.trim();
  if (!trimmed) return;
  const translated = t(trimmed, locale);
  if (translated === trimmed) return;
  const start = raw.indexOf(trimmed);
  node.nodeValue = raw.slice(0, start) + translated + raw.slice(start + trimmed.length);
}

export function translateElement(root, locale = activeLocale) {
  if (!root || language(locale) === 'de' || typeof document === 'undefined') return root;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  nodes.forEach((node) => translateNode(node, locale));

  const elements = [];
  if (root.nodeType === 1) elements.push(root);
  root.querySelectorAll?.('[title],[aria-label],[placeholder],[data-label]').forEach((el) => elements.push(el));
  for (const el of elements) {
    if (el.closest?.('[data-i18n-ignore]')) continue;
    for (const attr of ['title','aria-label','placeholder','data-label']) {
      if (!el.hasAttribute?.(attr)) continue;
      const value = el.getAttribute(attr);
      const translated = t(value, locale);
      if (translated !== value) el.setAttribute(attr, translated);
    }
  }
  return root;
}
