import assert from 'node:assert/strict';
import fs from 'node:fs';
import { renderCategories } from '../assets/js/views/categories.js';
import { renderSetupGuide } from '../assets/js/views/setup.js';
import { renderFixedCosts } from '../assets/js/views/fixed-costs.js';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
const sql=read('supabase/migrations/20261020161000_category_unique_active_siblings.sql');
for(const table of ['transactions','merchants','recurring_rules','budgets','bills','contracts','insurance_policies','categorization_rules','categories'])
 assert.ok(sql.includes('public.'+table),'cannot archive duplicates referenced by '+table);
assert.match(sql,/CREATE UNIQUE INDEX IF NOT EXISTS categories_unique_active_siblings_v1/);
assert.match(sql,/WHERE is_archived=false/);
assert.doesNotMatch(sql.split('\n').filter(line=>!line.trim().startsWith('--')).join('\n'),/\bDELETE\b|DROP TABLE|TRUNCATE/i);
const root={id:'legal',kind:'expense',name:'Rechts- & Gerichtskosten',parent_id:null};
const child={id:'court',kind:'expense',name:'Gerichtskosten',parent_id:'legal'};
const overview=renderCategories({categories:[root,child],categoryView:'main',canWrite:true});
assert.match(overview,/data-form="category-rename-inline"/);
assert.match(overview,/data-action="category-edit" data-id="court"/);
assert.match(overview,/data-action="category-add-child" data-id="legal"/);
assert.doesNotMatch(overview,/data-action="category-add-child" data-id="court"/);
const settings=renderCategories({categories:[root,child],categoryView:'settings',canWrite:true});
assert.match(settings,/Unterkategorie von Rechts- &amp; Gerichtskosten/);
assert.match(settings,/data-target="category-create"/);
const fixed=renderFixedCosts({canWrite:true,household:{country_code:'DE',base_currency:'EUR'}});
for(const direction of ['income','expense','transfer'])assert.ok(fixed.includes('data-direction="'+direction+'"'));
assert.doesNotMatch(fixed,/Position hinzufügen|Einzelne Rechnungen/);
const setup=renderSetupGuide({canWrite:true,household:{country_code:'DE',base_currency:'EUR'},profile:{locale:'de-DE'}});
assert.doesNotMatch(setup,/data-form="setup-income-create"|data-form="setup-expense-create"/);
const main=read('assets/js/main.js');
const css=read('assets/css/layout.css');
assert.match(main,/className='onboarding-return'/);
assert.match(main,/href="\/setup"/);
assert.match(main,/classList\.toggle\('onboarding-mode'/);
assert.match(css,/body\.onboarding-mode \.sidebar/);
assert.match(main,/starterInstallRuns=new Map\(\)/);
assert.match(main,/await financeApi\.updateCategory\(id,\{name:nextName\}\)/);
console.log('Ana full-flow and non-destructive category database safeguards OK');
